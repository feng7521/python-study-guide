"""
============================================================
第 1 课：认识 Python + 基础语法
============================================================
内容：print()、变量、运算符、缩进、注释、标识符
"""

print('=' * 50)
print('第 1 课：认识 Python 并运行你的第一行代码')
print('=' * 50)

# ---------- 1.1 print() 输出 ----------
print('\n--- 1.1 print() ---')
print('你好, Python!')      # print() 把内容显示到屏幕上

# ---------- 1.2 变量 ----------
print('\n--- 1.2 变量 ---')
name = '小明'               # 用 = 给变量赋值
age = 25
print(name, '今年', age, '岁')

# ---------- 1.3 运算符 ----------
print('\n--- 1.3 运算符 ---')
print('1 + 2 + 3 =', 1 + 2 + 3)
print('8 * 7 =', 8 * 7)
print('100 / 3 =', 100 / 3)

# ---------- 1.4 缩进 ----------
print('\n--- 1.4 缩进 ---')
if True:
    print('这行前面有4个空格')  # 属于 if 里面
    print('这行也有4个空格')
print('这行没有缩进')           # 不属于 if，一定会执行

# ---------- 1.5 注释 ----------
print('\n--- 1.5 注释 ---')
# 这是单行注释，Python 不会执行它
'''
这是多行注释
可以写很多行
用三个引号包起来
'''
print('注释不会影响代码运行')

# ---------- 1.6 标识符命名规则 ----------
print('\n--- 1.6 标识符 ---')
# 合法的变量名
legal_name = '张三'
_age_2 = 18
_private = '秘密'
print(f'合法变量名: {legal_name}, {_age_2}, {_private}')

# 不合法的变量名（不要这样写）:
# 2name = '错误'     # 数字开头
# my-name = '错误'   # 包含连字符
# if = '错误'        # 关键字

print('\n第1课结束！你已学会：print(), 变量, 运算符, 缩进, 注释, 命名规则')
